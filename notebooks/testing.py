class NoduleVolumeDataset(Dataset):

    def __init__(
        self,
        volume_dict,
        vol_ids,
        threshold_val=0.0
    ):

        self.volume_dict = volume_dict
        self.vol_ids = vol_ids
        self.threshold_val = threshold_val

    def __len__(self):
        return len(self.vol_ids)

    def __getitem__(self, idx):

        vol_id = self.vol_ids[idx]

        slice_paths = self.volume_dict[vol_id]

        if not slice_paths:
            raise RuntimeError(
                f"No slices found for volume {vol_id}"
            )

        slices_resized = []

        for image_path in slice_paths:

            try:
                img_raw = io.imread(
                    image_path,
                    as_gray=True
                ).astype(np.float32)

            except Exception as e:
                raise RuntimeError(
                    f"Failed loading slice:\n"
                    f"Volume: {vol_id}\n"
                    f"File: {image_path}\n"
                    f"Error: {e}"
                )

            if img_raw.size == 0:
                raise ValueError(
                    f"Empty image:\n"
                    f"{image_path}"
                )

            # ---------------------------------------------
            # Initial scaling
            # ---------------------------------------------

            if img_raw.max() > 1.0:
                img = img_raw / 255.0
            else:
                img = img_raw.copy()

            # ---------------------------------------------
            # Threshold
            # ---------------------------------------------

            if self.threshold_val > 0.0:

                img[img < self.threshold_val] = 0.0

            # ---------------------------------------------
            # Exact baseline 2D resizing
            # ---------------------------------------------

            img_tensor = torch.from_numpy(img).unsqueeze(0).unsqueeze(0)

            resized_tensor = F.interpolate(
                img_tensor,
                size=(64, 64),
                mode="bilinear",
                align_corners=False
            ).squeeze(0).squeeze(0)

            slices_resized.append(resized_tensor)

        # ---------------------------------------------
        # Stack slices
        # ---------------------------------------------

        volume_3d = torch.stack(
            slices_resized,
            dim=0
        )

        # Shape:
        # (1, 1, Depth, 64, 64)

        volume_tensor = (
            volume_3d
            .unsqueeze(0)
            .unsqueeze(0)
        )

        # ---------------------------------------------
        # Depth interpolation
        # ---------------------------------------------

        volume_resized = F.interpolate(
            volume_tensor,
            size=(16, 64, 64),
            mode="trilinear",
            align_corners=False
        ).squeeze(0)

        # ---------------------------------------------
        # Per-volume min-max normalization
        # ---------------------------------------------

        min_val = volume_resized.min()
        max_val = volume_resized.max()

        if max_val > min_val:

            volume_normalized = (
                volume_resized - min_val
            ) / (
                max_val - min_val
            )

        else:

            volume_normalized = torch.zeros_like(
                volume_resized
            )

        # Autoencoder target = input
        return (
            volume_normalized,
            volume_normalized
        )


