class Simple3DAutoencoder(nn.Module):

    def __init__(self):

        super().__init__()

        self.encoder = nn.Sequential(

            nn.Conv3d(
                1,
                16,
                kernel_size=3,
                padding=1
            ),

            nn.ReLU(True),

            nn.MaxPool3d(2, 2),

            nn.Conv3d(
                16,
                32,
                kernel_size=3,
                padding=1
            ),

            nn.ReLU(True),

            nn.MaxPool3d(2, 2)
        )

        self.decoder = nn.Sequential(

            nn.ConvTranspose3d(
                32,
                16,
                kernel_size=2,
                stride=2
            ),

            nn.ReLU(True),

            nn.ConvTranspose3d(
                16,
                1,
                kernel_size=2,
                stride=2
            ),

            nn.Sigmoid()
        )

    def forward(self, x):
        return self.decoder(
            self.encoder(x)
        )


