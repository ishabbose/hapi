def train_and_eval(
    threshold_val,
    num_epochs=10,
    lr=1e-3,
    batch_size=4
):

    set_seed(42)

    train_dataset = NoduleVolumeDataset(
        raw_volumes,
        train_ids,
        threshold_val=threshold_val
    )

    val_dataset = NoduleVolumeDataset(
        raw_volumes,
        val_ids,
        threshold_val=threshold_val
    )

    test_dataset = NoduleVolumeDataset(
        raw_volumes,
        test_ids,
        threshold_val=threshold_val
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False
    )

    model = Simple3DAutoencoder().to(device)

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=lr
    )

    criterion = nn.MSELoss()

    best_val_loss = float("inf")
    best_model_state = None

    print("\n" + "=" * 70)
    print(
        f"THRESHOLD = {threshold_val:.2f}"
    )
    print("=" * 70)

    for epoch in range(num_epochs):

        model.train()

        total_train_loss = 0.0

        for x, y in train_loader:

            x = x.to(device)
            y = y.to(device)

            optimizer.zero_grad()

            output = model(x)

            loss = criterion(
                output,
                y
            )

            loss.backward()

            optimizer.step()

            total_train_loss += (
                loss.item()
                * x.size(0)
            )

        train_loss = (
            total_train_loss
            / len(train_dataset)
        )

        # ---------------------------------------------
        # Validation
        # ---------------------------------------------

        model.eval()

        total_val_loss = 0.0

        with torch.no_grad():

            for x, y in val_loader:

                x = x.to(device)
                y = y.to(device)

                output = model(x)

                loss = criterion(
                    output,
                    y
                )

                total_val_loss += (
                    loss.item()
                    * x.size(0)
                )

        val_loss = (
            total_val_loss
            / len(val_dataset)
        )

        print(
            f"Epoch {epoch+1:02d}/{num_epochs} | "
            f"Train MSE: {train_loss:.6f} | "
            f"Val MSE: {val_loss:.6f}"
        )

        # ---------------------------------------------
        # Best checkpoint
        # ---------------------------------------------

        if val_loss < best_val_loss:

            best_val_loss = val_loss

            best_model_state = copy.deepcopy(
                model.state_dict()
            )

    # ---------------------------------------------
    # Test using best validation checkpoint
    # ---------------------------------------------

    model.load_state_dict(
        best_model_state
    )

    model.eval()

    total_test_loss = 0.0

    with torch.no_grad():

        for x, y in test_loader:

            x = x.to(device)
            y = y.to(device)

            output = model(x)

            loss = criterion(
                output,
                y
            )

            total_test_loss += (
                loss.item()
                * x.size(0)
            )

    test_loss = (
        total_test_loss
        / len(test_dataset)
    )

    return best_val_loss, test_loss


