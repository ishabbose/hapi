class ParametricNoduleVolumeDataset(Dataset):

    def __init__(
        self,
        volume_dict,
        volume_ids,
        threshold=0.0
    ):
        self.volume_dict = volume_dict
        self.volume_ids = volume_ids
        self.threshold = threshold

    def __len__(self):
        return len(self.volume_ids)

    def __getitem__(self, idx):

        volume_id = self.volume_ids[idx]

        slice_paths = self.volume_dict[volume_id]

        if not slice_paths:
            raise RuntimeError(
                f"No slices found for {volume_id}"
            )

        resized_slices = []

        for path in slice_paths:

            img_raw = io.imread(
                path,
                as_gray=True
            ).astype(np.float32)

            # Conditional scaling
            if img_raw.max() > 1.0:
                img = img_raw / 255.0
            else:
                img = img_raw.copy()

            # ONLY experimental transformation
            if self.threshold > 0.0:
                img = np.where(
                    img < self.threshold,
                    0.0,
                    img
                ).astype(np.float32)

            # Exact baseline 2D interpolation
            img_tensor = torch.from_numpy(img).unsqueeze(0).unsqueeze(0)

            resized = F.interpolate(
                img_tensor,
                size=(64, 64),
                mode="bilinear",
                align_corners=False
            ).squeeze(0).squeeze(0)

            resized_slices.append(resized)

        # Stack slices
        volume_3d = torch.stack(
            resized_slices,
            dim=0
        )

        # Add batch + channel dimensions
        volume_tensor = (
            volume_3d
            .unsqueeze(0)
            .unsqueeze(0)
        )

        # Exact baseline depth interpolation
        volume_resized = F.interpolate(
            volume_tensor,
            size=(16, 64, 64),
            mode="trilinear",
            align_corners=False
        ).squeeze(0)

        # Per-volume min-max normalization
        min_val = volume_resized.min()
        max_val = volume_resized.max()

        if max_val > min_val:
            volume_norm = (
                volume_resized - min_val
            ) / (
                max_val - min_val
            )
        else:
            volume_norm = torch.zeros_like(
                volume_resized
            )

        # Autoencoder target = input
        return volume_norm, volume_norm


