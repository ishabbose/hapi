def compute_dataset_raw_coverage(
    threshold_val
):

    if threshold_val == 0.0:
        return 0.0

    total_pixels = 0
    below_threshold = 0

    for volume_id in all_vol_ids:

        for image_path in raw_volumes[volume_id]:

            img_raw = io.imread(
                image_path,
                as_gray=True
            ).astype(np.float32)

            if img_raw.max() > 1.0:

                img = img_raw / 255.0

            else:

                img = img_raw

            total_pixels += img.size

            below_threshold += np.sum(
                img < threshold_val
            )

    if total_pixels == 0:
        return 0.0

    return (
        below_threshold
        / total_pixels
        * 100.0
    )


