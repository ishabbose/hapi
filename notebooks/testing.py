def run_controlled_experiment(
    threshold,
    epochs=10,
    batch_size=4,
    learning_rate=1e-3
):

    # Same initialization for both conditions
    set_seed(42)

    train_dataset = ParametricNoduleVolumeDataset(
        raw_volumes,
        train_ids,
        threshold=threshold
    )

    val_dataset = ParametricNoduleVolumeDataset(
        raw_volumes,
        val_ids,
        threshold=threshold
    )

    test_dataset = ParametricNoduleVolumeDataset(
        raw_volumes,
        test_ids,
        threshold=threshold
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False
    )

    model = Simple3DAutoencoder().to(device)

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=learning_rate
    )

    criterion = nn.MSELoss()

    best_val_loss = float("inf")
    best_model_state = None
    best_epoch = None

    epoch_records = []

    print("\n" + "=" * 70)
    print(
        f"RUNNING THRESHOLD = {threshold:.2f}"
    )
    print("=" * 70)

    for epoch in range(1, epochs + 1):

        # -------------------------
        # Training
        # -------------------------

        model.train()

        total_train_loss = 0.0

        for x, y in train_loader:

            x = x.to(device)
            y = y.to(device)

            optimizer.zero_grad()

            output = model(x)

            loss = criterion(
                output,
                y
            )

            loss.backward()

            optimizer.step()

            total_train_loss += (
                loss.item()
                * x.size(0)
            )

        train_mse = (
            total_train_loss
            / len(train_dataset)
        )

        # -------------------------
        # Validation
        # -------------------------

        model.eval()

        total_val_loss = 0.0

        with torch.no_grad():

            for x, y in val_loader:

                x = x.to(device)
                y = y.to(device)

                output = model(x)

                loss = criterion(
                    output,
                    y
                )

                total_val_loss += (
                    loss.item()
                    * x.size(0)
                )

        val_mse = (
            total_val_loss
            / len(val_dataset)
        )

        epoch_records.append(
            {
                "epoch": epoch,
                "train_mse": train_mse,
                "val_mse": val_mse
            }
        )

        print(
            f"Epoch {epoch:02d}/{epochs} | "
            f"Train MSE: {train_mse:.6f} | "
            f"Val MSE: {val_mse:.6f}"
        )

        # Save best validation checkpoint
        if val_mse < best_val_loss:

            best_val_loss = val_mse
            best_epoch = epoch

            best_model_state = copy.deepcopy(
                model.state_dict()
            )

    # -----------------------------------------------------
    # Restore BEST validation checkpoint
    # -----------------------------------------------------

    model.load_state_dict(
        best_model_state
    )

    # -----------------------------------------------------
    # Evaluate BEST MODEL on train set
    # -----------------------------------------------------

    model.eval()

    best_train_loss = 0.0

    with torch.no_grad():

        for x, y in train_loader:

            x = x.to(device)
            y = y.to(device)

            output = model(x)

            loss = criterion(
                output,
                y
            )

            best_train_loss += (
                loss.item()
                * x.size(0)
            )

    best_train_mse = (
        best_train_loss
        / len(train_dataset)
    )

    # -----------------------------------------------------
    # Evaluate BEST MODEL on test set
    # -----------------------------------------------------

    total_test_loss = 0.0

    with torch.no_grad():

        for x, y in test_loader:

            x = x.to(device)
            y = y.to(device)

            output = model(x)

            loss = criterion(
                output,
                y
            )

            total_test_loss += (
                loss.item()
                * x.size(0)
            )

    test_mse = (
        total_test_loss
        / len(test_dataset)
    )

    print(
        f"\nBest epoch: {best_epoch}"
    )

    print(
        f"Best validation MSE: "
        f"{best_val_loss:.6f}"
    )

    print(
        f"Test MSE from best model: "
        f"{test_mse:.6f}"
    )

    return {
        "best_epoch": best_epoch,
        "train_mse": best_train_mse,
        "val_mse": best_val_loss,
        "test_mse": test_mse,
        "history": epoch_records
    }


